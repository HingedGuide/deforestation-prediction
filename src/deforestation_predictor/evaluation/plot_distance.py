"""
Script Name: Plot Spatial Distance Results

Description:
    This script reads the CSV output generated by the evaluate_distance.py script
    and creates a professional, publication-ready grouped bar chart showing
    F0.5, Precision, and Recall across different spatial distance categories.
"""

import argparse
import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path

def plot_distance_metrics(csv_path, output_path=None):
    """
    Reads the distance evaluation CSV and generates a grouped bar chart.
    
    Args:
        csv_path (str): Path to the CSV file containing the metrics.
        output_path (str, optional): Path to save the generated plot. 
                                     If None, it shows the plot interactively.
    """
    # 1. Load the data
    print(f"Loading data from {csv_path}...")
    df = pd.read_csv(csv_path)
    
    # Ensure the categories are in the correct logical order
    category_order = [
        'Within past def. (0m)', 
        'Adjacent (<= 400m)', 
        '> 400m and <= 800m', 
        '> 800m'
    ]
    # Filter the dataframe to only include the known categories and order them
    df['Distance Category'] = pd.Categorical(df['Distance Category'], categories=category_order, ordered=True)
    df = df.sort_values('Distance Category').dropna(subset=['Distance Category'])
    
    # 2. Setup the plot parameters
    categories = df['Distance Category'].tolist()
    x = np.arange(len(categories))  # the label locations
    width = 0.25  # the width of the bars
    
    fig, ax = plt.subplots(figsize=(10, 6))
    
    # 3. Create the grouped bars
    # We plot Precision, Recall, and F0.5
    rects1 = ax.bar(x - width, df['Precision'], width, label='Precision', color='#4C72B0', edgecolor='black', zorder=3)
    rects2 = ax.bar(x, df['Recall'], width, label='Recall', color='#55A868', edgecolor='black', zorder=3)
    rects3 = ax.bar(x + width, df['F0.5'], width, label='F0.5 Score', color='#C44E52', edgecolor='black', zorder=3)
    
    # 4. Customizing the plot for a professional (thesis) look
    ax.set_ylabel('Score', fontsize=12, fontweight='bold')
    ax.set_xlabel('Distance to Past Deforestation', fontsize=12, fontweight='bold')
    ax.set_title('Model Performance by Distance to Past Deforestation', fontsize=14, fontweight='bold', pad=15)
    ax.set_xticks(x)
    ax.set_xticklabels(categories, fontsize=11)
    ax.set_ylim(0, 1.05) # Leave a bit of room at the top for labels
    ax.legend(loc='upper right', fontsize=11, framealpha=0.9)
    
    # Add a subtle grid behind the bars for readability
    ax.grid(axis='y', linestyle='--', alpha=0.7, zorder=0)
    
    # Remove top and right spines for a cleaner look
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)

    # 5. Add value labels on top of the bars
    def autolabel(rects):
        """Attach a text label above each bar in *rects*, displaying its height."""
        for rect in rects:
            height = rect.get_height()
            ax.annotate(f'{height:.2f}',
                        xy=(rect.get_x() + rect.get_width() / 2, height),
                        xytext=(0, 3),  # 3 points vertical offset
                        textcoords="offset points",
                        ha='center', va='bottom', fontsize=9)

    autolabel(rects1)
    autolabel(rects2)
    autolabel(rects3)

    plt.tight_layout()
    
    # 6. Save or show the plot
    if output_path:
        out_file = Path(output_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        plt.savefig(out_file, dpi=300, bbox_inches='tight')
        print(f"Plot saved successfully to {out_file}")
    else:
        plt.show()

def main():
    parser = argparse.ArgumentParser(description="Plot Distance Evaluation Results")
    parser.add_argument("--csv_path", type=str, required=True, help="Path to the distance_results.csv file")
    parser.add_argument("--output_path", type=str, default="results/distance_performance_plot.png", help="Where to save the PNG plot")
    
    args = parser.parse_args()
    
    plot_distance_metrics(args.csv_path, args.output_path)

if __name__ == "__main__":
    main()